const { chromium, devices } = require('playwright');
(async () => {
  const b = await chromium.launch(); const pg = await (await b.newContext({ ...devices['iPhone 13'], deviceScaleFactor:1 })).newPage();
  const errs=[]; pg.on('pageerror',e=>errs.push(e.message)); pg.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
  const ok=(c,m)=>console.log((c?'PASS ':'FAIL ')+m);
  await pg.goto('http://localhost:8765/_test_live.html#home'); await pg.waitForSelector('.vc'); await pg.waitForTimeout(400);
  await pg.screenshot({path:'test/e-home.png'}); await pg.screenshot({path:'test/e-home-full.png',fullPage:true});
  ok(await pg.isVisible('#chat .chatform'),'home has chat with input');
  ok((await pg.$$eval('.vc',e=>e.length))===3,'home shows 3 Claude picks');
  await pg.click('.nav a[data-tab="eat"]'); await pg.waitForSelector('#vlist .vc');
  const total=await pg.$$eval('#vlist .vc',e=>e.length); ok(total>90,'eat list count '+total);
  const names=async()=>pg.$$eval('#vlist .vc h3',e=>e.slice(0,6).map(x=>x.textContent));
  console.log('  claude:', (await names()).join(' / '));
  await pg.screenshot({path:'test/e-eat.png'});
  await pg.click('[data-sort="rating"]'); await pg.waitForTimeout(100);
  const stars=await pg.$$eval('#vlist .vc .stars',e=>e.map(x=>parseFloat(x.textContent.replace('★',''))));
  ok(stars.length>10 && stars.every((v,i)=>i===0||stars[i-1]>=v),'rating sort descending: '+stars.slice(0,8).join(','));
  await pg.click('[data-sort="dist"]'); await pg.waitForTimeout(100);
  const d=await pg.$$eval('#vlist .vc',e=>e.map(x=>{const m=x.querySelector('.meta').textContent.match(/도보 (\d+)분/);return m?+m[1]:999}));
  ok(d.every((v,i)=>i===0||d[i-1]<=v),'distance sort ascending: '+d.slice(0,8).join(','));
  await pg.click('[data-sort="price"]'); await pg.waitForTimeout(100);
  const pr=await pg.$$eval('#vlist .vc .money',e=>e.map(x=>x.textContent.match(/₱([\d,]+)/)).filter(Boolean).map(m=>+m[1].replace(/,/g,'')));
  ok(pr.length>20 && pr.every((v,i)=>i===0||pr[i-1]<=v),'price sort ascending: '+pr.slice(0,8).join(','));
  await pg.click('[data-ecat="korean"]'); await pg.waitForTimeout(100); console.log('  korean:', (await names()).join(' / '));
  await pg.click('[data-ecat="all"]'); await pg.fill('#q','망고'); await pg.waitForTimeout(800);
  const dh=await pg.$$eval('#dishes .dish',e=>e.length); ok(dh>3,'dish search 망고 → '+dh+' dishes');
  await pg.screenshot({path:'test/e-search.png'});
  await pg.fill('#q','Cyma'); await pg.waitForTimeout(300); await pg.click('#vlist .vc [data-open] >> nth=0'); await pg.waitForSelector('#menuBox .dish');
  const items=await pg.$$eval('#menuBox .dish',e=>e.length); ok(items>50,'Cyma full menu items '+items);
  const A=()=>pg.locator('#menuBox .qty .add:visible'); await A().nth(0).click(); await A().nth(0).click(); await A().nth(1).click();
  const bar=await pg.$eval('.orderbar',e=>e.innerText); ok(/3개/.test(bar),'order bar: '+bar.replace(/\n/g,' | '));
  await pg.screenshot({path:'test/e-menu.png'});
  await pg.click('[data-ordersheet]'); await pg.waitForSelector('.osheet'); ok((await pg.$$eval('.osheet li',e=>e.length))===2,'order sheet lists 2 lines');
  await pg.screenshot({path:'test/e-order.png'});
  await pg.click('[data-shareorder]'); await pg.waitForTimeout(500);
  ok((await pg.$$eval('.msg .t',e=>e.map(x=>x.textContent).join('|'))).includes('[주문] Cyma'),'order shared to family chat');
  await pg.goto('http://localhost:8765/_test_live.html#p-v-quara'); await pg.waitForTimeout(600);
  console.log('  quara title:', await pg.$eval('#sheet .t',e=>e.textContent).catch(()=>'none'));
  const hs=await pg.evaluate(()=>[document.documentElement.scrollWidth,window.innerWidth]); ok(hs[0]<=hs[1],'no hscroll');
  console.log('errors', JSON.stringify(errs)); await b.close();
})();
